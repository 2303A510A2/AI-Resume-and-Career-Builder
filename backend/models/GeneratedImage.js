const mongoose = require('mongoose');

// A real generated image, owned by the user who asked for it.
//
// The bytes are stored as a base64 data URL (same approach the upload path
// already uses for Document.imageData) so an image can never be served from a
// public, guessable URL: GET /api/ai/images/:id is JWT-protected and
// ownership-checked. The raw data is `select: false` so it never leaks into a
// list/normal query, and no client payload ever contains the bytes.
const generatedImageSchema = new mongoose.Schema(
  {
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    conversationId: { type: mongoose.Schema.Types.ObjectId, ref: 'Chat', default: null, index: true },

    // Exactly what the user asked for, and exactly what was sent to the provider.
    userPrompt: { type: String, required: true },
    prompt: { type: String, required: true },
    // The same request without the quality suffix, so a conversational follow-up
    // ("make it at night") merges onto the original request, not the suffixed one.
    basePrompt: { type: String, default: '' },
    revisedPrompt: { type: String, default: '' },
    isFollowUp: { type: Boolean, default: false },

    provider: { type: String, required: true },
    model: { type: String, default: '' },
    mimeType: { type: String, default: 'image/png' },
    bytes: { type: Number, default: 0 },
    // Real pixel dimensions, read from the generated bytes, so the client can
    // preserve the image's proportions instead of guessing.
    width: { type: Number, default: 0 },
    height: { type: Number, default: 0 },

    // base64 data URL of the real image (never returned directly to a client).
    imageData: { type: String, required: true, select: false },
  },
  { timestamps: true }
);

generatedImageSchema.index({ userId: 1, createdAt: -1 });

// Safe projection for API responses: metadata + how to fetch the bytes, no data.
generatedImageSchema.methods.toClientJSON = function toClientJSON() {
  return {
    id: this._id,
    prompt: this.prompt,
    userPrompt: this.userPrompt,
    provider: this.provider,
    model: this.model,
    mimeType: this.mimeType,
    bytes: this.bytes,
    width: this.width,
    height: this.height,
    isFollowUp: this.isFollowUp,
    createdAt: this.createdAt,
  };
};

module.exports = mongoose.model('GeneratedImage', generatedImageSchema);